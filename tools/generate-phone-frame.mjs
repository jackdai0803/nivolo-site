// Derive the chassis from Xcode's exact framebuffer contour. Centered
// strokes, clipped to the outside, give the bezel an even physical width.
import fs from 'node:fs';

const root = new URL('../', import.meta.url);
const quarter = Array.from({ length: 25 }, (_, i) => {
  const angle = i / 24 * Math.PI / 2;
  return [Math.sqrt(Math.sin(angle)), Math.sqrt(Math.cos(angle))];
});
const n = (value) => Number(value.toFixed(3));
function contour(x, y, w, h, radius) {
  const r = Math.min(radius, w / 2, h / 2);
  const points = [];
  for (let corner = 0; corner < 4; corner++) {
    for (const [sin, cos] of quarter) {
      const s = sin * r, t = cos * r;
      points.push(corner === 0 ? [x + w - r + s, y + r - t]
        : corner === 1 ? [x + w - r + t, y + h - r + s]
          : corner === 2 ? [x + r - s, y + h - r + t]
            : [x + r - t, y + r - s]);
    }
  }
  return `M${n(x + r)} ${n(y)} ` + points.map(([px, py]) => `L${n(px)} ${n(py)}`).join(' ') + ' Z';
}

const mask = fs.readFileSync(new URL('assets/device-iphone16-screen-mask.svg', root), 'utf8');
const screen = mask.match(/<path[^>]* d="([^"]+)"/)[1];
const buttons = [[4, 462, 26, 154], [4, 689, 26, 218], [4, 943, 26, 217],
  [1422, 798, 26, 380], [1422, 1760, 26, 220]];
const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/generate-phone-frame.mjs. The screen opening,
     black bezel and titanium band share Xcode's continuous contour.
     Outward strokes keep the black bezel 28px and the band 16px wide. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1452 2956">
  <defs>
    <linearGradient id="band" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#F2F3F5"/><stop offset="0.1" stop-color="#D4D6DA"/>
      <stop offset="0.5" stop-color="#B6BAC0"/><stop offset="0.9" stop-color="#D4D6DA"/>
      <stop offset="1" stop-color="#F2F3F5"/>
    </linearGradient>
    <linearGradient id="btn" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0" stop-color="#9EA3AA"/><stop offset="0.5" stop-color="#D2D4D8"/>
      <stop offset="1" stop-color="#9EA3AA"/>
    </linearGradient>
    <path id="screen-contour" d="${screen}" transform="translate(66 44)"/>
    <mask id="screen-window" maskUnits="userSpaceOnUse" x="0" y="0" width="1452" height="2956">
      <rect width="1452" height="2956" fill="white"/>
      <path d="${screen}" transform="translate(66 44)" fill="black"/>
    </mask>
  </defs>
  <g fill="url(#btn)" stroke="rgba(20,23,28,0.25)" stroke-width="2">
    ${buttons.map(([x, y, w, h]) => `<path d="${contour(x, y, w, h, 12)}"/>`).join('\n    ')}
  </g>
  <g fill="none" mask="url(#screen-window)">
    <use href="#screen-contour" stroke="rgba(20,23,28,0.3)" stroke-width="88"/>
    <use href="#screen-contour" stroke="url(#band)" stroke-width="86"/>
    <use href="#screen-contour" stroke="rgba(255,255,255,0.4)" stroke-width="58"/>
    <use href="#screen-contour" stroke="#0A0B0D" stroke-width="56"/>
  </g>
  <!-- The physical Dynamic Island remains a capsule. -->
  <rect x="540" y="77" width="372" height="110" rx="55" fill="#050607"/>
</svg>
`;
fs.writeFileSync(new URL('assets/iphone16-frame.svg', root), svg);
console.log('Generated phone chassis with a uniform contour-derived bezel.');
