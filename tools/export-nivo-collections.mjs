// Refresh website collection membership from the app's shared catalog.
import { writeFileSync } from 'node:fs';
import { NIVO_COLLECTIONS } from '../../pebble-app/src/series/catalog.js';
import { ZH_EXTRA } from '../../pebble-app/src/i18n_extra.js';
const collections = NIVO_COLLECTIONS.map(({ id, name, ids }) => ({ id, name, zh: ZH_EXTRA[name] || name, ids }));
writeFileSync(new URL('../assets/nivo-collections.js', import.meta.url), `// Generated by tools/export-nivo-collections.mjs; edit the app catalog.\nexport const collections = ${JSON.stringify(collections, null, 2)};\n`);
console.log(`Exported ${collections.length} collections from the app.`);
